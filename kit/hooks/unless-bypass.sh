#!/usr/bin/env bash
# Обёртка-гейт: в режиме bypassPermissions (длинные автономные прогоны) обёрнутый хук не запускается вообще.
# В остальных режимах он запускается как раньше.
#
#   unless-bypass.sh '<команда хука>'
#
# Зачем: удобство и скорость (подсказки, напоминания, пересборка команд) в автономном прогоне только мешают.
# Одна обёртка вместо проверки режима в каждом скрипте.
# НЕ оборачивать стражей безопасности (safety-guard, защита секретов): они должны работать всегда.
# Для них — bypass-ask-to-deny.sh или голая команда.
#
# Команда приходит первым аргументом; stdin буферизуется и отдаётся ей же.
set -uo pipefail

input=$(cat)

if [ "$(jq -r '.permission_mode // empty' <<<"$input" 2>/dev/null)" = "bypassPermissions" ]; then
  exit 0
fi

exec bash -c "$1" <<<"$input"
