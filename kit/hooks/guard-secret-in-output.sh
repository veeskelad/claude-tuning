#!/usr/bin/env bash
# PostToolUse-страж: ищет СЕКРЕТ В ВЫВОДЕ инструмента.
#
# Зачем, если есть guard-secret-{read,file-read,dump}.sh: те судят по КОМАНДЕ и ПУТИ.
# Имя файла о содержимом не говорит: `cat` XML-конфига базы — путь чистый, верб обычный,
# а внутри пароль открытым текстом. Ни один PreToolUse-страж сработать не мог в принципе.
#
# Постфактум вывод уже не отменить — цель хука не «спасти», а НЕ ДАТЬ ПРОМОЛЧАТЬ:
# поднять инцидент немедленно, пока агент не поехал дальше как ни в чём не бывало.
# Отсюда deny-биас: лучше ложная тревога, чем тихо утёкший секрет.
set -uo pipefail

input=$(cat)

# Вывод берём целиком (tool_response любой формы), режем до 256 КБ.
# Упавшая команда (код выхода ≠ 0) приходит событием PostToolUseFailure: там вместо
# tool_response поле error с тем же выводом. так ключ однажды ушёл в транскрипт мимо хука:
# команда кончилась кодом 1.
# Base64-блобы (Read картинки или PDF отдаёт тело файла base64-строкой) — не текст, а шум,
# в котором шаблоны находят «секреты» по статистике: однотонные области JPEG кодируются
# повторами вида `ogCiAKIAogCi`, и `AKIA[0-9A-Z]{16}` совпадал посреди кадра — 9 ложных
# блокировок за один покадровый разбор 2026-09-21. От сплошного прогона ≥1000 символов
# base64-алфавита оставляем первые 24: этого хватает, чтобы `token=<длинное значение>`
# по-прежнему ловился правилом 3, а тело картинки в поиск не попадало.
# perl, а не sed/grep: у BSD-регекспов счётчик повторов ограничен 255.
out=$(printf '%s' "$input" | jq -r '.tool_response // .error // empty | if type=="string" then . else tostring end' 2>/dev/null \
  | perl -pe 's{([A-Za-z0-9+/_-]{24})[A-Za-z0-9+/_-]{976,}={0,2}}{$1<base64-blob>}g' | head -c 262144)
[ -z "$out" ] && exit 0

# Строки-плейсхолдеры: не значения, а ССЫЛКИ на них. Их не считаем утечкой.
# Сюда же — код, читающий секрет из окружения (`process.env.CH_PASSWORD`, `os.environ[...]`,
# `secretKeyRef`): там имя переменной, а не её значение. Без этого хук орал на каждый
# греп по config.ts — ложняк, замеченный сразу же после установки.
PLACEHOLDER='from_env|REDACTED|synthetic|\*\*\*|\$\{|\$\(|<no value>|CHANGEME|changeme|example|placeholder|sha256:|xxxx|\.\.\.|process\.env\.|os\.environ|getenv|secretKeyRef|valueFrom|z\.(coerce|string|number)|=[[:space:]]*<|\{\{|скрыт|hidden|masked|укажи|задай'

hits=""
add() { hits="${hits:+$hits; }$1"; }

# 1. Приватные ключи — всегда утечка, без оговорок.
if printf '%s' "$out" | grep -Eq -- '-----BEGIN [A-Z ]*PRIVATE KEY-----'; then
  add "приватный ключ"
fi

# 2. Пароль в XML-теге с реальным значением (<password>secret</password>, в т.ч. CDATA).
#    Пустой тег и from_env — не утечка.
#    CDATA обязателен в шаблоне: значение начинается с '<![CDATA[', и наивное [^<] его
#    пропускает — именно так первая версия хука провалила тест на своём же инциденте.
XML_PW='<password[^>]*>(<!\[CDATA\[)?[^]<[:space:]]'
if printf '%s' "$out" | grep -Eq "$XML_PW" \
   && ! printf '%s' "$out" | grep -E "$XML_PW" | grep -Eq "$PLACEHOLDER"; then
  add "пароль в XML"
fi

# 3. key=value / key: value с непустым значением от 8 символов.
#    Значение должно ВЫГЛЯДЕТЬ как credential, а не как код: [^"[:space:]]{8,} ловил
#    любые 8 непробельных символов, включая исходник регулярки-цензора
#    `(token=)([\w.\-]+)` — значение там начинается с `)(`, и хук ронял ревью eslint
#    на собственном имени параметра (ложняк 2026-07-29). Реальные секреты состоят из
#    букв/цифр/._-/+= (в т.ч. base64), скобок и слэшей регекспа в них не бывает.
#    Кавычка перед значением теперь любая — раньше только двойная, и секрет в одинарных
#    кавычках после двоеточия проходил мимо.
KV_RE='(password|passwd|pwd|secret|token|api[_-]?key|access[_-]?key|private[_-]?key)["'"'"'`]?[[:space:]]*[:=][[:space:]]*["'"'"'`]?[A-Za-z0-9_./+=-]{8,}'
# Код, а не значение (ложняки 2026-09-16 при ревью Python): справа путь атрибутов
# `token=settings.bot.admin_bot_token`, `api_key=core.payment.provider_api_key` или
# аннотация `access_key: SecretStr`. Сегменты пути только snake_case в нижнем регистре
# и начинаются с буквы: у JWT и base64 есть заглавные, у hex-секретов сегменты с цифры.
# Сравнение регистрозависимое (без -i), иначе `Abc.Def` из секрета сошёл бы за код.
# Одиночный идентификатор тоже код, если это слова через подчёркивание без цифр:
# `token = random_token()` (ложняк 2026-09-16). Случайный секрет из одних строчных
# букв с подчёркиваниями и без цифр практически не встречается.
# JS/TS (ложняки 2026-09-17): camelCase-идентификатор `token: humanVerificationToken`,
# `const token = getReferralToken ? …` и начало шаблонной строки `token: \`challenge-${n}\``
# (совпадение обрывается на `$`, значение кончается дефисом). В camelCase нет цифр и двух
# заглавных подряд; у случайного base62 такое почти не выпадает.
# Путь API/файла в нижнем регистре (`secret: /auth/login` в комментарии, ложняк 2026-09-25).
# Ложняки из каталога 2026-09-28: `_get_provider_key` (приватная функция), `APP_BOT_TOKEN`
# в markdown (ИМЯ переменной, а не значение), `apiKey: apiKey.key` (camelCase с атрибутом).
# Аннотации типов Python (ложняки 2026-09-25 на исходниках Python-проекта): `access_token: Optional[str]`,
# `api_key: Optional[str] = None` — совпадение обрывается на `[`, остаётся имя типа.
CODE_VALUE='[:=][[:space:]]*["'"'"'`]?(_[a-z]+(_[a-z]+)*|[A-Z][A-Z0-9]*(_[A-Z0-9]+)+|[a-z]+([A-Z][a-z]+)+(\.[A-Za-z_][A-Za-z0-9_]*)+|[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)+|[a-z]+(_[a-z]+)+|[a-z]+([A-Z][a-z]+)+|[a-z]+-|Secret(Str|Bytes)|(Optional|Union|Dict|List|Tuple|Callable|Mapping|Sequence)|/[a-z][a-z0-9_-]*(/[a-z0-9_-]+)+)$'
kv=$(printf '%s' "$out" | grep -Eio "$KV_RE" | grep -Eiv "$PLACEHOLDER" | grep -Ev "$CODE_VALUE" | head -1)
if [ -n "$kv" ]; then
  # Улика в отчёт, но без значения: буквы → a, цифры → 9, пунктуация как есть.
  # Форма мгновенно отличает секрет (`aaa999aa-aa99`) от кода (`)([\aa.\-]+)`) —
  # без неё каждый ложняк приходится диагностировать вслепую, как этот.
  shape=$(printf '%s' "$kv" | tr 'A-Za-z' 'a' | tr '0-9' '9')
  add "похоже на ключ со значением (${shape})"
fi

# 4. Токены с опознаваемым префиксом — самодостаточные улики.
#    У AKIA, в отличие от остальных префиксов, все символы входят в base64-алфавит, поэтому
#    ему нужны границы слова: настоящий ключ AWS стоит отдельно, а не посреди base64-строки
#    (короткие блобы вроде data:-URI иконок фильтр выше не режет).
if printf '%s' "$out" | grep -Eq '(sk-or-v1-[a-f0-9]{32,}|(sk|rk)_live_[A-Za-z0-9]{16,}|whsec_[A-Za-z0-9]{20,}|apify_api_[A-Za-z0-9]{30,}|AQVN[A-Za-z0-9_-]{30,}|t1\.[A-Za-z0-9_-]{40,}\.[A-Za-z0-9_-]{20,}|hf_[A-Za-z0-9]{30,}|ntn_[A-Za-z0-9]{30,}|glpat-[A-Za-z0-9_-]{20,}|y0_[A-Za-z0-9_-]{20,}|hvs\.[A-Za-z0-9_-]{20,}|xox[baprs]-[A-Za-z0-9-]{10,}|ghp_[A-Za-z0-9]{30,}|sk-[A-Za-z0-9]{20,})' \
   || printf '%s' "$out" | grep -Eq '(^|[^A-Za-z0-9+/=_-])AKIA[0-9A-Z]{16}([^A-Za-z0-9+/=_-]|$)'; then
  add "токен по префиксу (sk-, ghp_, xox… и т.п.)"
fi

[ -z "$hits" ] && exit 0

reason="🔐 В выводе, похоже, секрет: ${hits}
Если это настоящее значение — сказать пользователю, что и где утекло, и предложить сменить ключ. Если ложная тревога (пример, заглушка, код) — сказать об этом одной строкой и продолжить."

# Для PostToolUseFailure модель получает текст через additionalContext (схема событий CLI),
# decision/reason оставлены общими для обоих событий.
event=$(printf '%s' "$input" | jq -r '.hook_event_name // "PostToolUse"' 2>/dev/null)
jq -n --arg r "$reason" --arg e "$event" '{
  decision: "block",
  reason: $r,
  systemMessage: "🔐 В выводе, похоже, секрет — агент проверит и скажет."
} + (if $e == "PostToolUseFailure" then {hookSpecificOutput: {hookEventName: $e, additionalContext: $r}} else {} end)'
exit 0
