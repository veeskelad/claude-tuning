#!/usr/bin/env python3
"""MCP-серверы и права к ним: Claude → Codex. Источник правды — Claude.

  ~/.claude.json  mcpServers (глобальные и проектные)    → [mcp_servers.<имя>]
  .claude/settings.json, правила permissions для mcp__*  → tools.<инструмент>.approval_mode
      allow → "approve", ask → "prompt", deny → disabled_tools

Codex получает управляемый блок в конце ~/.codex/config.toml и <проект>/.codex/config.toml (только у
проектов, где этот файл уже есть, проект доверен в Claude и файл не попадёт в git — в блоке бывают
ключи MCP). Сервер, который Codex описывает сам вне блока, остаётся как есть: синхронизируются только
права к его инструментам, deny туда не применить — об этом строка в отчёте. Значения ключей
переносятся из файла в файл и не печатаются. Нет ~/.codex/config.toml — скрипт ничего не делает.

  sync_from_claude.py           записать блоки, напечатать короткий отчёт (только имена)
  sync_from_claude.py --check   только отчёт, код 1 — если что-то поменялось бы
  sync_from_claude.py --quiet   без отчёта

Зовёт его claude_bridge.py на каждом SessionStart Codex; выключить — CLAUDE_PARITY_MCP_SYNC=0.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python до 3.11: синхронизации нет, остальной мост работает
    print("sync_from_claude.py: нужен Python 3.11+ (tomllib), MCP не синхронизирован", file=sys.stderr)
    raise SystemExit(0)

HOME = Path.home()
_CFG = os.environ.get("CLAUDE_CONFIG_DIR")
CLAUDE_DIR = Path(_CFG).expanduser() if _CFG else HOME / ".claude"
CLAUDE_JSON = CLAUDE_DIR / ".claude.json" if _CFG else HOME / ".claude.json"
CODEX_HOME = Path(os.environ.get("CODEX_HOME") or HOME / ".codex").expanduser()
BEGIN = "# >>> claude-sync: generated by claude-parity/sync_from_claude.py, do not edit >>>"
END = "# <<< claude-sync <<<"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
MODE = {"allow": "approve", "ask": "prompt"}


def load_json(path: Path) -> dict:
    try:
        value = json.loads(path.read_text())
    except (OSError, ValueError):
        return {}
    return value if isinstance(value, dict) else {}


def toml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else toml_str(key)


def outside_block(path: Path) -> tuple[str, dict]:
    text = path.read_text() if path.exists() else ""
    rest = BLOCK.sub("", text)
    try:
        return rest, tomllib.loads(rest)
    except tomllib.TOMLDecodeError:
        return rest, {}


def committable(path: Path) -> bool:
    """Файл внутри git-репозитория и не в .gitignore — блок с ключами туда не пишется."""
    try:
        r = subprocess.run(["git", "-C", str(path.parent), "check-ignore", "-q", str(path)],
                           capture_output=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return r.returncode == 1  # 0 — игнорируется, 128 — не репозиторий


def server_toml(name: str, spec: dict, deny: list[str]) -> list[str]:
    lines = [f"[mcp_servers.{toml_key(name)}]"]
    if spec.get("type") in ("http", "sse") or spec.get("url"):
        lines.append(f"url = {toml_str(spec['url'])}")
        headers = spec.get("headers") or {}
        if headers:
            lines.append("http_headers = { " + ", ".join(f"{toml_str(k)} = {toml_str(str(v))}" for k, v in headers.items()) + " }")
    else:
        lines.append(f"command = {toml_str(spec['command'])}")
        if spec.get("args"):
            lines.append("args = [" + ", ".join(toml_str(str(a)) for a in spec["args"]) + "]")
        env = spec.get("env") or {}
        if env:
            lines.append("env = { " + ", ".join(f"{toml_key(k)} = {toml_str(str(v))}" for k, v in env.items()) + " }")
    if deny:
        lines.append("disabled_tools = [" + ", ".join(toml_str(t) for t in deny) + "]")
    return lines


def permissions(settings: Path) -> dict[str, dict[str, list[str]]]:
    """{сервер: {"allow": [...], "ask": [...], "deny": [...]}} из правил mcp__сервер__инструмент."""
    perms = load_json(settings).get("permissions") or {}
    out: dict[str, dict[str, list[str]]] = {}
    for kind in ("allow", "ask", "deny"):
        for rule in perms.get(kind) or []:
            m = re.fullmatch(r"mcp__([^_]+(?:_[^_]+)*?)__([A-Za-z0-9_-]+)", str(rule))
            if m:
                out.setdefault(m.group(1), {}).setdefault(kind, []).append(m.group(2))
    return out


def build(target: Path, servers: dict, perms: dict, inherited: dict | None,
          spilled: frozenset = frozenset()) -> tuple[str, list[str], dict]:
    """Новый текст файла, строки отчёта и права к серверам, которые описаны только глобально.

    Проектный файл бывает общим для нескольких машин, глобальный конфиг — свой у каждой: таблица tools
    для сервера, которого в файле нет, ломает Codex там, где этого сервера нет («invalid transport»).
    Такие права уходят в глобальный блок."""
    rest, existing = outside_block(target)
    defined = {n.lower(): n for n in (existing.get("mcp_servers") or {})}
    is_project = inherited is not None
    switched_off = {n.lower() for n, v in (existing.get("mcp_servers") or {}).items()
                    if isinstance(v, dict) and v.get("enabled") is False}
    lines: list[str] = []
    report: list[str] = []
    owned: dict[str, str] = {}
    for name, spec in sorted(servers.items()):
        if name.lower() in defined:
            continue  # описан вне блока (свой вариант или enabled = false) — не трогать
        deny = (perms.get(name) or {}).get("deny") or []
        lines += server_toml(name, spec, deny) + [""]
        owned[name.lower()] = name
        report.append(f"сервер {name}")
    spill: dict[str, dict] = {}
    for server, kinds in sorted(perms.items()):
        key = server.lower()
        if is_project and key not in owned and (key not in defined or key in switched_off):
            spill[server] = kinds  # решится по глобальному конфигу этой машины
            continue
        codex_name = owned.get(key) or defined.get(key)
        if not codex_name:
            if not is_project and key in spilled:
                report.append(f"права {server}: сервера нет в Codex на этой машине, пропущены")
                continue
            report.append(f"⚠ права для {server}: такого сервера нет ни в Claude, ни в Codex")
            continue
        if kinds.get("deny") and key not in owned:
            report.append(f"⚠ {codex_name}: deny {len(kinds['deny'])} шт. не применить — сервер описан вне блока, "
                          "добавь disabled_tools вручную")
        for kind in ("allow", "ask"):
            for tool in kinds.get(kind) or []:
                lines += [f"[mcp_servers.{toml_key(codex_name)}.tools.{toml_key(tool)}]",
                          f"approval_mode = {toml_str(MODE[kind])}", ""]
        n = len(kinds.get("allow") or []) + len(kinds.get("ask") or [])
        if n:
            report.append(f"права {codex_name}: {n}")
    block = "\n".join([BEGIN, *lines, END]) + "\n" if lines else ""
    text = rest.rstrip("\n") + ("\n\n" + block if block else "\n")
    return text, report, spill


def targets() -> tuple[list[tuple[Path, dict, dict, dict | None]], list[str]]:
    cj = load_json(CLAUDE_JSON)
    global_cfg = CODEX_HOME / "config.toml"
    if not global_cfg.is_file():
        return [], []
    out: list[tuple[Path, dict, dict, dict | None]] = [
        (global_cfg, cj.get("mcpServers") or {}, permissions(CLAUDE_DIR / "settings.json"), None)]
    skipped: list[str] = []
    for proj, info in sorted((cj.get("projects") or {}).items()):
        cfg = Path(proj) / ".codex/config.toml"
        if not isinstance(info, dict) or not info.get("hasTrustDialogAccepted") or not cfg.is_file():
            continue
        perms = permissions(Path(proj) / ".claude/settings.json")
        servers = info.get("mcpServers") or {}
        if not (servers or perms):
            continue
        if committable(cfg):
            skipped.append(f"⚠ {cfg}: файл не в .gitignore — блок не пишу (в нём бывают ключи MCP); "
                           "добавь .codex/config.toml в .gitignore проекта")
            continue
        out.append((cfg, servers, perms, {}))
    return out, skipped


def main() -> int:
    check = "--check" in sys.argv
    quiet = "--quiet" in sys.argv
    changed = False
    planned, skipped = targets()
    spill: dict[str, dict] = {}
    results = []
    for target, servers, perms, inherited in planned[::-1]:  # сначала проекты, глобальный (индекс 0) — последним
        if inherited is None:
            for name, kinds in spill.items():
                merged = perms.setdefault(name, {})
                for kind, tools in kinds.items():
                    merged[kind] = sorted(set(merged.get(kind, [])) | set(tools))
        text, report, extra = build(target, servers, perms, inherited,
                                    frozenset(k.lower() for k in spill) if inherited is None else frozenset())
        for name, kinds in extra.items():
            for kind, tools in kinds.items():
                spill.setdefault(name, {}).setdefault(kind, [])
                spill[name][kind] = sorted(set(spill[name][kind]) | set(tools))
        results.append((target, text, report))
    for target, text, report in results:
        old = target.read_text() if target.exists() else ""
        if text == old:
            continue
        try:
            tomllib.loads(text)
        except tomllib.TOMLDecodeError as e:
            print(f"✗ {target}: собранный TOML невалиден ({e}), файл не тронут")
            continue
        changed = True
        if not check:
            mode = target.stat().st_mode & 0o777 if target.exists() else 0o600
            tmp = target.with_suffix(".toml.sync-tmp")
            tmp.write_text(text)
            os.chmod(tmp, mode)
            os.replace(tmp, target)
        if not quiet:
            print(f"{'нужно обновить' if check else 'обновлён'} {target}: " + "; ".join(report))
    if not quiet:
        for line in skipped:
            print(line)
    return 1 if check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
